"""Stub fixtures that let the three demo hypotheses finish the existing pipeline.

Registration does not add a scientific stage. It only points known statements
at fixtures the services already accept.
"""

from __future__ import annotations

from app.schemas.claim import ClaimProvenance, EpistemicStatus, EvidenceOrigin
from app.schemas.critic import (
    ConventionalExplanation,
    CritiqueIssue,
    IssueCategory,
    IssueSeverity,
    assemble_report,
)
from app.schemas.hypothesis import HypothesisInput
from app.schemas.run import ExampleCard, ExampleList
from app.schemas.observable import PredictedDifference
from app.schemas.parser import (
    ClaimType,
    ClaimVariable,
    ExtractionConfidence,
    MissingDefinition,
    ParsedClaim,
    ParserResult,
)
from app.services.fixtures import (
    GOLDEN_CLAIM_IDS,
    GOLDEN_CRITICS,
    GOLDEN_PARSERS,
    normalize_statement,
)
from app.services.m2_fixtures import (
    CASE_MASS,
    GOLDEN_M2_CLAIM_IDS,
    GOLDEN_NULLS,
    GOLDEN_OBSERVABLES,
)
from app.services.m3_fixtures import GOLDEN_PLANS, synthetic_plan
from app.services.m4_fixtures import CASE_QUANT, _claim, _null, _observable

VAGUE_FIELD = "A previously unknown field changes mechanical oscillation frequency."
SYNTHETIC_NOTICE = "Synthetic demonstration — not experimental evidence."


def demo_examples() -> ExampleList:
    """Return the three fixed demos. The list is not generated by a model."""

    return ExampleList(
        examples=[
            ExampleCard(
                example_id="pendulum",
                title="Qualitative pendulum claim",
                purpose="A period-versus-mass comparison whose finite falsifier is not yet defined.",
                statement=CASE_MASS,
            ),
            ExampleCard(
                example_id="vague_field",
                title="Vague frontier claim",
                purpose="A named effect that does not yet identify a measurement.",
                statement=VAGUE_FIELD,
            ),
            ExampleCard(
                example_id="synthetic",
                title="Synthetic quantitative claim",
                purpose="A labeled fixture whose stated curves can reach a finite comparison.",
                statement=CASE_QUANT,
                notice=SYNTHETIC_NOTICE,
            ),
        ]
    )


def register_demo_fixtures() -> None:
    """Attach demo statements to existing stub builders. Repeated calls are harmless."""

    mass = normalize_statement(CASE_MASS)
    quant = normalize_statement(CASE_QUANT)
    GOLDEN_PARSERS[mass] = _pendulum_parser
    GOLDEN_CRITICS[mass] = _pendulum_critic
    GOLDEN_CLAIM_IDS[mass] = {"c1"}
    GOLDEN_PARSERS[quant] = _quantitative_parser
    GOLDEN_CRITICS[quant] = _quantitative_critic
    GOLDEN_CLAIM_IDS[quant] = {"c1"}
    GOLDEN_NULLS[quant] = lambda: _null("H0 is y = 2*x + 1.")
    GOLDEN_OBSERVABLES[quant] = lambda: _observable(
        h0="y follows 2*x + 1.",
        h1="y follows 2*x + 1 + 0.1*x*x.",
        difference=PredictedDifference.INCREASE,
        discriminating=True,
    )
    GOLDEN_M2_CLAIM_IDS[quant] = {"c1"}
    GOLDEN_PLANS[quant] = synthetic_plan


def _pendulum_parser(hypothesis: HypothesisInput) -> ParserResult:
    return ParserResult(
        claims=[
            ParsedClaim(
                claim_id="c1",
                statement=hypothesis.statement,
                claim_type=ClaimType.CAUSAL,
                variables=[
                    ClaimVariable(name="bob mass", defined=True),
                    ClaimVariable(name="pendulum length", defined=True),
                    ClaimVariable(name="oscillation period", defined=True),
                ],
                is_operational=True,
                missing_definitions=[
                    MissingDefinition(
                        statement="A numeric small-angle tolerance is not stated.",
                        critical=False,
                    )
                ],
                provenance=ClaimProvenance(
                    origin=EvidenceOrigin.ASSUMED,
                    observable="oscillation period",
                ),
                epistemic_status=EpistemicStatus.HYPOTHESIS,
                confidence=ExtractionConfidence.MEDIUM,
            )
        ],
        parser_notes=["The period-versus-mass comparison is identifiable."],
    )


def _pendulum_critic():
    return assemble_report(
        issues=[
            CritiqueIssue(
                issue_id="i1",
                severity=IssueSeverity.MAJOR,
                category=IssueCategory.MISSING_CONTROL,
                statement=(
                    "H1 does not state a quantitative mass-to-period relationship "
                    "or a minimum effect size."
                ),
                affected_claim_ids=["c1"],
                evidence_basis="The hypothesis says the period changes and gives no magnitude.",
                blocking=False,
            )
        ],
        conventional_explanations=[
            ConventionalExplanation(
                explanation_id="e1",
                statement=(
                    "An ideal small-angle pendulum has a period set by length and gravity."
                ),
                affected_claim_ids=["c1"],
                evidence_basis="The conventional ideal period does not contain bob mass.",
            )
        ],
        required_clarifications=[
            "Specify a quantitative mass-to-period relationship or a minimum effect size."
        ],
        summary="The comparison is identifiable, and H1 is not yet quantitative.",
    )


def _quantitative_parser(hypothesis: HypothesisInput) -> ParserResult:
    parsed = _claim(hypothesis.statement)
    return parsed


def _quantitative_critic():
    return assemble_report(
        issues=[
            CritiqueIssue(
                issue_id="i1",
                severity=IssueSeverity.MINOR,
                category=IssueCategory.CONVENTIONAL_EXPLANATION,
                statement="The stated H0 is the linear response y = 2*x + 1.",
                affected_claim_ids=["c1"],
                evidence_basis="The synthetic text states H0 directly.",
                blocking=False,
            )
        ],
        conventional_explanations=[
            ConventionalExplanation(
                explanation_id="e1",
                statement="H0 is y = 2*x + 1 over the stated range.",
                affected_claim_ids=["c1"],
                evidence_basis="The synthetic text states that equation.",
            )
        ],
        summary="Synthetic demonstration. The text defines both curves and a 0.1 uncertainty.",
    )
